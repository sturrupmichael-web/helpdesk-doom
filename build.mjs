// Builds index.html: one self-contained page with the game's JavaScript (Three.js included),
// the maps and the icon inlined, so it runs on any static host. Edit the code under src/,
// play it with dev.html, then run `npm run build`. `?map=file.json` still loads a map file.

import { build } from 'esbuild';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const js = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});
const maps = Object.fromEntries(
  readdirSync('maps').filter((f) => f.endsWith('.json')).map((f) => [f.replace(/\.json$/, ''), JSON.parse(readFileSync(`maps/${f}`, 'utf8'))]),
);
const icon = `data:image/png;base64,${readFileSync('icons/icon-192.png').toString('base64')}`;
const html = readFileSync('dev.html', 'utf8')
  .replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '')
  .replace('href="icons/icon-192.png"', () => `href="${icon}"`)
  .replace('<script type="module" src="src/main.js"></script>', () =>
    `<script>globalThis.__DOOM_MAPS__ = ${JSON.stringify(maps).replaceAll('</', '<\\/')};</script>\n  <script type="module">\n${js.outputFiles[0].text.replaceAll('</script', '<\\/script')}</script>`,
  )
  .replace('<title>', '<!-- Generated by build.mjs from dev.html and src/. Do not edit by hand. -->\n  <title>');
writeFileSync('index.html', withCsp(html));
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB, maps: ${Object.keys(maps).join(', ')}`);

// Content Security Policy: the page may only run its own (inline, hashed) scripts, and
// only fetches from its own site (a map file given with ?map=).
// blob: and data: images are for canvas textures.
function withCsp(page) {
  const hashes = [...page.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`,
  );
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  return page.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`);
}
